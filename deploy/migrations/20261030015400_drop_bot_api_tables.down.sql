-- 按删除前的最终形状（0060 … 20261020010000 叠加后的结果）重建三张空表。
-- 队列内容不可恢复：回滚只恢复结构，旧网关从空队列开始。
CREATE TABLE public.bot_api_updates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_user_id bigint NOT NULL,
    update_kind varchar(32) NOT NULL,
    peer_type varchar(16) NOT NULL,
    peer_id bigint NOT NULL,
    message_id integer NOT NULL,
    source_pts integer NOT NULL DEFAULT 0,
    date integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    callback_query_id bigint NOT NULL DEFAULT 0,
    callback_user_id bigint NOT NULL DEFAULT 0,
    callback_chat_instance bigint NOT NULL DEFAULT 0,
    callback_data bytea,
    callback_inline_dc_id integer NOT NULL DEFAULT 0,
    callback_inline_owner_id bigint NOT NULL DEFAULT 0,
    callback_inline_message_id integer NOT NULL DEFAULT 0,
    callback_inline_access_hash bigint NOT NULL DEFAULT 0,
    ephemeral_payload jsonb,
    pre_checkout_payload jsonb,
    member_payload jsonb,
    CONSTRAINT bot_api_updates_source_pts_check CHECK (source_pts >= 0),
    CONSTRAINT bot_api_updates_bot_user_id_fkey FOREIGN KEY (bot_user_id) REFERENCES public.bots(bot_user_id) ON DELETE CASCADE,
    CONSTRAINT bot_api_updates_kind_check CHECK (
        update_kind IN ('message', 'edited_message', 'callback_query', 'pre_checkout_query',
                        'my_chat_member', 'chat_member')
    ),
    CONSTRAINT bot_api_updates_peer_type_check CHECK (
        peer_type IN ('user', 'channel')
        OR (update_kind IN ('callback_query', 'pre_checkout_query') AND peer_type = '')
    ),
    CONSTRAINT bot_api_updates_peer_id_check CHECK (
        peer_id > 0
        OR (update_kind IN ('callback_query', 'pre_checkout_query') AND peer_id = 0)
    ),
    CONSTRAINT bot_api_updates_message_id_check CHECK (
        message_id > 0
        OR (update_kind IN ('callback_query', 'pre_checkout_query', 'my_chat_member', 'chat_member')
            AND message_id = 0)
    ),
    CONSTRAINT bot_api_updates_callback_shape_check CHECK (
        (update_kind = 'callback_query'
            AND callback_query_id <> 0
            AND callback_user_id > 0
            AND callback_chat_instance <> 0
            AND COALESCE(octet_length(callback_data), 0) <= 64
            AND source_pts = 0
            AND (
                (peer_type IN ('user', 'channel') AND peer_id > 0 AND message_id > 0
                    AND callback_inline_dc_id = 0 AND callback_inline_owner_id = 0
                    AND callback_inline_message_id = 0 AND callback_inline_access_hash = 0)
                OR
                (peer_type = '' AND peer_id = 0 AND message_id = 0
                    AND callback_inline_dc_id > 0 AND callback_inline_owner_id > 0
                    AND callback_inline_message_id > 0 AND callback_inline_access_hash <> 0)
            ))
        OR
        (update_kind = 'pre_checkout_query'
            AND pre_checkout_payload IS NOT NULL
            AND callback_query_id = 0 AND callback_user_id = 0
            AND callback_chat_instance = 0 AND callback_data IS NULL
            AND callback_inline_dc_id = 0 AND callback_inline_owner_id = 0
            AND callback_inline_message_id = 0 AND callback_inline_access_hash = 0
            AND source_pts = 0
            AND peer_type = '' AND peer_id = 0 AND message_id = 0)
        OR
        (update_kind IN ('message', 'edited_message')
            AND peer_type IN ('user', 'channel') AND peer_id > 0 AND message_id > 0
            AND callback_query_id = 0 AND callback_user_id = 0
            AND callback_chat_instance = 0 AND callback_data IS NULL
            AND callback_inline_dc_id = 0 AND callback_inline_owner_id = 0
            AND callback_inline_message_id = 0 AND callback_inline_access_hash = 0)
        OR
        (update_kind IN ('my_chat_member', 'chat_member')
            AND peer_type = 'channel' AND peer_id > 0 AND message_id = 0 AND source_pts = 0
            AND callback_query_id = 0 AND callback_user_id = 0
            AND callback_chat_instance = 0 AND callback_data IS NULL
            AND callback_inline_dc_id = 0 AND callback_inline_owner_id = 0
            AND callback_inline_message_id = 0 AND callback_inline_access_hash = 0
            AND ephemeral_payload IS NULL AND pre_checkout_payload IS NULL
            AND member_payload IS NOT NULL)
    ),
    CONSTRAINT bot_api_updates_ephemeral_shape_check CHECK (
        ephemeral_payload IS NULL
        OR (
            peer_type = 'channel'
            AND peer_id > 0
            AND message_id > 0
            AND source_pts = 0
            AND jsonb_typeof(ephemeral_payload) = 'object'
            AND jsonb_typeof(ephemeral_payload -> 'Message') = 'object'
            AND (ephemeral_payload #>> '{Message,ID}') IS NOT NULL
            AND (ephemeral_payload #>> '{Message,Peer,Type}') IS NOT NULL
            AND (ephemeral_payload #>> '{Message,Peer,ID}') IS NOT NULL
            AND (ephemeral_payload #>> '{Message,SenderUserID}') IS NOT NULL
            AND (ephemeral_payload #>> '{Message,ReceiverUserID}') IS NOT NULL
            AND (ephemeral_payload #>> '{Message,Version}') IS NOT NULL
            AND NOT ((ephemeral_payload -> 'Message') ?| ARRAY[
                'RandomID', 'OriginDevice', 'PayloadHash', 'CreatedAt', 'Deleted'
            ])
            AND (
                NOT (ephemeral_payload ? 'ReplyTo')
                OR (
                    jsonb_typeof(ephemeral_payload -> 'ReplyTo') = 'object'
                    AND NOT ((ephemeral_payload -> 'ReplyTo') ?| ARRAY[
                        'RandomID', 'OriginDevice', 'PayloadHash', 'CreatedAt', 'Deleted'
                    ])
                )
            )
            AND (ephemeral_payload #>> '{Message,ID}')::integer = message_id
            AND (ephemeral_payload #>> '{Message,Peer,Type}') = peer_type
            AND (ephemeral_payload #>> '{Message,Peer,ID}')::bigint = peer_id
            AND (
                (update_kind = 'callback_query'
                    AND (ephemeral_payload #>> '{Message,SenderUserID}')::bigint = bot_user_id)
                OR
                (update_kind IN ('message', 'edited_message')
                    AND (ephemeral_payload #>> '{Message,ReceiverUserID}')::bigint = bot_user_id)
            )
            AND (ephemeral_payload #>> '{Message,Version}')::bigint > 0
        )
    ),
    CONSTRAINT bot_api_updates_member_shape_check CHECK (
        member_payload IS NULL
        OR (
            update_kind IN ('my_chat_member', 'chat_member')
            AND jsonb_typeof(member_payload) = 'object'
            AND (member_payload #>> '{chat,Type}') = peer_type
            AND (member_payload #>> '{chat,ID}')::bigint = peer_id
            AND (member_payload #>> '{new,user_id}') IS NOT NULL
            AND (
                (update_kind = 'my_chat_member'
                    AND (member_payload #>> '{new,user_id}')::bigint = bot_user_id)
                OR
                (update_kind = 'chat_member'
                    AND (member_payload #>> '{new,user_id}')::bigint <> bot_user_id)
            )
        )
    )
);

CREATE INDEX bot_api_updates_bot_scan_idx ON public.bot_api_updates (bot_user_id, id);
CREATE INDEX bot_api_updates_retention_idx ON public.bot_api_updates (date, id);
CREATE INDEX bot_api_updates_created_retention_idx ON public.bot_api_updates (created_at, id);

CREATE UNIQUE INDEX bot_api_updates_message_source_unique
    ON public.bot_api_updates (bot_user_id, update_kind, peer_type, peer_id, message_id, source_pts)
    WHERE update_kind IN ('message', 'edited_message') AND ephemeral_payload IS NULL;

CREATE UNIQUE INDEX bot_api_updates_callback_query_unique
    ON public.bot_api_updates (bot_user_id, callback_query_id)
    WHERE update_kind = 'callback_query';

CREATE UNIQUE INDEX bot_api_updates_ephemeral_version_unique
    ON public.bot_api_updates (
        bot_user_id,
        update_kind,
        peer_type,
        peer_id,
        message_id,
        ((ephemeral_payload #>> '{Message,Version}')::bigint)
    )
    WHERE update_kind IN ('message', 'edited_message') AND ephemeral_payload IS NOT NULL;

CREATE UNIQUE INDEX bot_api_updates_pre_checkout_unique
    ON public.bot_api_updates (bot_user_id, ((pre_checkout_payload #>> '{id}')::bigint))
    WHERE update_kind = 'pre_checkout_query';

CREATE TABLE public.bot_api_update_states (
    bot_user_id bigint PRIMARY KEY,
    confirmed_update_id bigint NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    allowed_updates text[],
    cursor_initialized boolean NOT NULL DEFAULT false,
    poll_owner text NOT NULL DEFAULT '',
    poll_expires_at timestamptz,
    CONSTRAINT bot_api_update_states_confirmed_check CHECK (confirmed_update_id >= 0),
    CONSTRAINT bot_api_update_states_bot_user_id_fkey FOREIGN KEY (bot_user_id) REFERENCES public.bots(bot_user_id) ON DELETE CASCADE,
    CONSTRAINT bot_api_update_states_allowed_updates_check CHECK (
        allowed_updates IS NULL
        OR array_position(allowed_updates, NULL) IS NULL
    ),
    CONSTRAINT bot_api_update_states_poll_lease_check CHECK (
        (poll_owner = '' AND poll_expires_at IS NULL)
        OR
        (poll_owner <> '' AND poll_expires_at IS NOT NULL)
    )
);

CREATE TABLE public.bot_api_webhooks (
    bot_user_id bigint PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    url text NOT NULL,
    secret_token varchar(256) NOT NULL DEFAULT '',
    max_connections integer NOT NULL DEFAULT 40,
    allowed_updates text[],
    failure_count integer NOT NULL DEFAULT 0,
    last_error_date integer NOT NULL DEFAULT 0,
    last_error_message varchar(512) NOT NULL DEFAULT '',
    next_attempt_at timestamptz NOT NULL DEFAULT now(),
    delivery_owner text NOT NULL DEFAULT '',
    delivery_expires_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT bot_api_webhooks_url_check CHECK (length(url) BETWEEN 1 AND 2048),
    CONSTRAINT bot_api_webhooks_max_connections_check CHECK (max_connections BETWEEN 1 AND 100),
    CONSTRAINT bot_api_webhooks_failure_count_check CHECK (failure_count >= 0),
    CONSTRAINT bot_api_webhooks_allowed_updates_check CHECK (
        allowed_updates IS NULL OR array_position(allowed_updates, NULL) IS NULL
    ),
    CONSTRAINT bot_api_webhooks_delivery_lease_check CHECK (
        (delivery_owner = '' AND delivery_expires_at IS NULL)
        OR (delivery_owner <> '' AND delivery_expires_at IS NOT NULL)
    )
);

CREATE INDEX bot_api_webhooks_due_idx
    ON public.bot_api_webhooks (next_attempt_at, bot_user_id);
